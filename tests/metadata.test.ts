import { expect, test } from "vitest";
import { extractMetadata } from "@/lib/server/metadata";

test("extractMetadata returns duration and MIME type for MP3 with ID3v2", () => {
  const buffer = new Uint8Array([
    0x49, 0x44, 0x33, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x24,
    0x54, 0x4C, 0x45, 0x4E, 0x00, 0x00, 0x00, 0x04, 0x00, 0x00,
    0x31, 0x32, 0x33, 0x34, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00,
  ]);
  const result = extractMetadata(buffer, "audio/mpeg");
  expect(result.format).toBe("mp3");
  expect(result.durationMs).toBe(1234);
});

test("extractMetadata returns duration for M4A with moov atom", () => {
  const buffer = new Uint8Array([
    0x00, 0x00, 0x00, 0x3c,
    0x6d, 0x6f, 0x6f, 0x76,
    0x00, 0x00, 0x00, 0x20,
    0x6d, 0x76, 0x68, 0x64,
    0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x03, 0xe8,
    0x00, 0x00, 0x03, 0xe8,
  ]);
  const result = extractMetadata(buffer, "audio/mp4");
  expect(result.format).toBe("m4a");
  expect(result.durationMs).toBe(1000);
});

test("extractMetadata handles unknown format gracefully", () => {
  const buffer = new Uint8Array([0x00, 0x01, 0x02, 0x03]);
  const result = extractMetadata(buffer, "audio/unknown");
  expect(result.format).toBe("unknown");
  expect(result.durationMs).toBeUndefined();
  expect(result.durationSeconds).toBeUndefined();
});